import { useState } from 'react';
import { useStore } from '../lib/store';
import { api } from '../lib/api';
import { PageHeader } from '../components/Layout';
import { Badge, Card, Empty, Notice, Toggle, Field } from '../components/ui';
import { fmtTime, fmtRel } from '../lib/format';

const CATS: [string, string][] = [
  ['preliminary', 'Preliminary liquidity sweep'],
  ['confirmation', 'ELF confirmation (sweep → BOS → displacement)'],
  ['entry', 'Entry-ready setup'],
  ['outcome', 'Stop-loss / Target 1 / Target 2 (theoretical trade)'],
  ['invalidation', 'Setup filtered, invalidated or expired'],
  ['feed', 'Data-feed disconnection / recovery'],
  ['plan', 'Your monitored trade plans'],
];

export function Alerts() {
  const { app, saveApp, alerts, unread, markRead, toast, alertStreamConnected } = useStore();
  const [webhook, setWebhook] = useState<string | null>(null);
  const [perm, setPerm] = useState<NotificationPermission | 'unsupported'>('Notification' in window ? Notification.permission : 'unsupported');
  if (!app) return null;
  const prefs = app.alerts;

  const save = async (p: Record<string, unknown>) => {
    const r = await saveApp({ alerts: p });
    if (!r.ok) toast({ title: 'Not saved', message: (r.errors ?? []).join('; '), kind: 'error' });
  };
  const askPermission = async () => {
    if (!('Notification' in window)) return;
    const r = await Notification.requestPermission();
    setPerm(r);
  };
  const test = async () => {
    const r = await api.post<{ ok: boolean; note: string }>('/api/alerts/test');
    toast({ title: r.ok ? 'Test alert sent' : 'Test alert muted', message: r.note, kind: r.ok ? 'success' : 'info' });
  };

  return (
    <>
      <PageHeader title="Alerts" sub={`${unread} unread · in-app stream ${alertStreamConnected ? 'connected' : 'disconnected'}`} right={<button className="btn" onClick={() => markRead()}>Mark all read</button>} />
      <div className="grid grid-2">
        <Card title="What to alert">
          <div className="seg wide" role="group">
            {(['all', 'preliminary', 'confirmation', 'entry', 'custom'] as const).map((p) => (
              <button key={p} className={prefs.preset === p ? 'on' : ''} onClick={() => save({ preset: p })}>
                {p === 'all' ? 'All' : p === 'preliminary' ? 'Preliminary' : p === 'confirmation' ? 'Confirmation only' : p === 'entry' ? 'Entry only' : 'Custom'}
              </button>
            ))}
          </div>
          <div className="stack">
            {CATS.map(([k, label]) => {
              const signalCat = k === 'preliminary' || k === 'confirmation' || k === 'entry';
              const locked = signalCat && prefs.preset !== 'custom';
              const presetVal = prefs.preset === 'all' ? true : prefs.preset === k;
              const checked = locked ? presetVal : (prefs.categories as any)[k];
              return <Toggle key={k} checked={checked} disabled={locked} onChange={(v) => save({ preset: prefs.preset, categories: { ...prefs.categories, [k]: v } })} label={label} />;
            })}
          </div>
          <p className="muted small">Each event alerts once (de-duplicated by a unique event key). Alerts are generated by the server for markets on your watch-list and any market currently open in a browser.</p>
        </Card>
        <Card title="Delivery">
          <Toggle checked={prefs.browserNotifications} onChange={(v) => save({ browserNotifications: v })} label="Browser notifications (while the app is open)" />
          <div className="row gap wrap">
            <span className="muted small">Permission: {perm}</span>
            {perm !== 'granted' && perm !== 'unsupported' && (
              <button className="btn btn-sm" onClick={askPermission}>
                Allow notifications
              </button>
            )}
            <button className="btn btn-sm" onClick={test}>
              Send test alert
            </button>
          </div>
          <Notice tone="info">
            In-app and browser notifications work only while the app is open in a tab. On iPhone, web notifications additionally require installing the app to the Home Screen (iOS 16.4+). For alerts while the
            app is closed, enable the server webhook below — it is sent by the server as long as the server is running.
          </Notice>
          <Field label="Webhook URL (HTTPS) — e.g. ntfy.sh topic, Slack or Discord incoming webhook" hint="A JSON POST with title, message and the full alert. Treat the URL as a secret.">
            <input value={webhook ?? prefs.webhook.url ?? ''} onChange={(e) => setWebhook(e.target.value)} placeholder="https://ntfy.sh/your-private-topic" />
          </Field>
          <div className="row gap wrap">
            <Toggle checked={prefs.webhook.enabled} onChange={(v) => save({ webhook: { enabled: v, url: (webhook ?? prefs.webhook.url) || null } })} label="Enable webhook" />
            <button className="btn btn-sm" onClick={() => save({ webhook: { enabled: prefs.webhook.enabled, url: (webhook ?? '').trim() || null } })}>
              Save URL
            </button>
          </div>
        </Card>
      </div>
      <Card title="History">
        {alerts.length === 0 ? (
          <Empty>No alerts yet. They appear when a qualifying event happens on a closed candle.</Empty>
        ) : (
          <ul className="alert-list">
            {alerts.map((a) => (
              <li key={a.id} className={a.read ? 'read' : ''} onClick={() => !a.read && markRead(a.id)}>
                <div className="row gap wrap">
                  <Badge tone={a.category === 'entry' ? 'accent' : a.category === 'feed' ? 'warn' : a.category === 'invalidation' ? 'bad' : 'info'}>{a.category}</Badge>
                  <strong>{a.title}</strong>
                  <span className="muted small grow" style={{ textAlign: 'right' }}>
                    {a.candleTime ? fmtTime(a.candleTime) : ''} · {fmtRel(a.createdAt)}
                  </span>
                </div>
                <pre className="alert-msg">{a.message}</pre>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </>
  );
}
